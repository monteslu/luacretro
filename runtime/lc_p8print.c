/* luacretro runtime: PICO-8 print() and the built-in font.
 *
 * A straight port of FAKE-08's printHelper.cpp print() plus the
 * Graphics::drawCharacter / drawCharacterFromBytes glyph blitters
 * (FAKE-08, MIT, jtothebell). Behaviour is FAKE-08's, quirks included,
 * because FAKE-08 is the oracle the fidelity harness diffs against:
 *  - only 0x5f58 (print attributes) is honoured; 0x5f59..0x5f5b are not
 *  - the tab stop defaults to 16px (\^s changes it), not 0x5f5a
 *  - glyph pixels ignore fill pattern and the 0x5f5e colour bitmask;
 *    the solid-background box goes through rectfill (which honours both)
 *  - \^1..\^9 and \^d pauses and \a audio are parsed and skipped
 *  - auto-scroll moves the real 0x6000 screen, not the remapped one
 *
 * Font: the PICO-8 font is CC0 (Lexaloffle). lc_p8_font is generated
 * from FAKE-08's source/fontdata.cpp (defaultFontBinaryData) by
 * gen-font.mjs in the luacretro internal scratch tree; do not edit the
 * table by hand. Layout matches the 0x5600 custom-font format: 8 bytes
 * per glyph, one byte per row, bit 0 = leftmost pixel; glyph 0 is the
 * font header (width 4, wide width 8, height 5).
 */
#include "lc_p8.h"

#define PM_ON      0x01
#define PM_PADDING 0x02
#define PM_WIDE    0x04
#define PM_TALL    0x08
#define PM_SOLIDBG 0x10
#define PM_INVERT  0x20
#define PM_STRIPEY 0x40
#define PM_CUSTOM  0x80

#define CUSTOM_FONT 0x5600

/* byte i of the string; FAKE-08 reads str[length] as 0 */
static inline uint8_t at(const uint8_t *s, uint32_t len, uint32_t i) {
  return i < len ? s[i] : 0;
}

/* P8SCII "p0" parameter digit: 0-9, then a.. = 10.. (uppercase reads 0) */
static uint8_t p0(uint8_t c) {
  uint8_t n = 0;
  if (c > 47 && c < 58) n = (uint8_t)(c - 48);
  if (c > 96) n = (uint8_t)(c - 87);
  return n;
}

/* strtol(buf, NULL, 16) over at most n bytes (a NUL also ends it). */
static int32_t hexnum(const uint8_t *s, uint32_t n) {
  uint32_t i = 0;
  int neg = 0;
  int32_t v = 0;
  while (i < n && (s[i] == ' ' || (s[i] >= 9 && s[i] <= 13))) i++;
  if (i < n && (s[i] == '+' || s[i] == '-')) neg = s[i++] == '-';
  if (i + 2 < n && s[i] == '0' && (s[i + 1] | 0x20) == 'x') {
    uint8_t c = s[i + 2];
    if ((c >= '0' && c <= '9') || ((c | 0x20) >= 'a' && (c | 0x20) <= 'f')) i += 2;
  }
  for (; i < n; i++) {
    uint8_t c = s[i];
    int d;
    if (c >= '0' && c <= '9') d = c - '0';
    else if ((c | 0x20) >= 'a' && (c | 0x20) <= 'f') d = (c | 0x20) - 'a' + 10;
    else break;
    v = v * 16 + d;
  }
  return neg ? -v : v;
}

/* the hex/size field starting at s[i]: substr(i, n) semantics */
static int32_t hexfield(const uint8_t *s, uint32_t len, uint32_t i, uint32_t n) {
  if (i >= len) return 0;
  if (n > len - i) n = len - i;
  return hexnum(s + i, n);
}

/* Poke raw bytes, dropping anything outside memory (FAKE-08 would
 * scribble past its buffer there). */
static void pokeb(int32_t addr, uint8_t v) {
  if (addr >= 0 && (uint32_t)addr < LC_P8_MEMSIZE) lc_p8mem[addr] = v;
}

static inline int in_clip(int x, int y) {
  return x >= lc_p8mem[P8_CLIP_XB] && x < lc_p8mem[P8_CLIP_XE] &&
         y >= lc_p8mem[P8_CLIP_YB] && y < lc_p8mem[P8_CLIP_YE];
}

/* setPixelNibble on the mapped screen buffer; clip can be poked past
 * 128, so the byte index is bounded against memory, not the screen. */
static void put_nibble(uint32_t base, int x, int y, uint8_t c) {
  uint32_t a = base + (((uint32_t)y << 6) | ((uint32_t)x >> 1));
  if (a >= LC_P8_MEMSIZE) return;
  uint8_t b = lc_p8mem[a];
  lc_p8mem[a] = (x & 1) ? (uint8_t)((b & 0x0f) | (c << 4)) : (uint8_t)((b & 0xf0) | (c & 0x0f));
}

/* Graphics::drawCharacterFromBytes. Returns the extra width through the
 * return value and the extra height through *eh. */
static int blit_glyph(const uint8_t *rows, int x, int y, uint8_t fg, uint8_t bg,
                      uint8_t mode, uint8_t cw, uint8_t chh, int *eh) {
  int ew = 0, wf = 1, hf = 1, stripey = 0, invert = 0, solid = 0;
  uint32_t base = (uint32_t)(lc_p8_screenbuf() - lc_p8mem);
  x -= p8_rd16(P8_CAMERA_X);
  y -= p8_rd16(P8_CAMERA_Y);
  *eh = 0;
  if (mode & PM_ON) {
    if (mode & PM_WIDE) { wf = 2; ew = cw; }
    if (mode & PM_TALL) { hf = 2; *eh = chh; }
    if (mode & PM_STRIPEY) stripey = 1;
    if (mode & PM_INVERT) invert = 1;
    if (mode & PM_SOLIDBG) solid = 1;
  }
  fg &= 0x0f;
  bg &= 0x0f;
  if (wf == 1 && hf == 1 && !invert && !solid) {
    /* the common case: plain glyph, visit only its set pixels */
    int xb = lc_p8mem[P8_CLIP_XB], xe = lc_p8mem[P8_CLIP_XE];
    int yb = lc_p8mem[P8_CLIP_YB], ye = lc_p8mem[P8_CLIP_YE];
    int rows_n = chh < 8 ? chh : 8;
    uint32_t mask = cw >= 8 ? 0xffu : ((1u << cw) - 1u);
    for (int ry = 0; ry < rows_n; ry++) {
      int ay = y + ry;
      if (ay < yb || ay >= ye) continue;
      uint32_t bits = rows[ry] & mask;
      for (int col = 0; bits; col++, bits >>= 1) {
        if (!(bits & 1)) continue;
        int ax = x + col;
        if (ax >= xb && ax < xe) put_nibble(base, ax, ay, fg);
      }
    }
    return ew;
  }
  /* only 8x8 of glyph data exists; larger cells are blank */
  for (int ry = 0; ry < chh * hf; ry++) {
    int row = ry / hf;
    if (row >= 8) continue;
    for (int rx = 0; rx < cw * wf; rx++) {
      int col = rx / wf;
      if (col >= 8) continue;
      int on = (rows[row] >> col) & 1;
      if (stripey && hf != 1 && (ry & 1)) on = 0;
      if (stripey && wf != 1 && (rx & 1)) on = 0;
      int ax = x + rx, ay = y + ry;
      if (!in_clip(ax, ay)) continue;
      if (invert) on = !on;
      if (on) put_nibble(base, ax, ay, fg);
      else if (solid) put_nibble(base, ax, ay, bg);
    }
  }
  return ew;
}

/* Graphics::drawCharacter: returns the extra advance (0 in any
 * PRINT_MODE_ON mode, where the caller's charWidth already says it). */
static int draw_char(uint8_t ch, int x, int y, uint8_t fg, uint8_t bg, uint8_t mode,
                     int fw, int fh) {
  int extra = 0, eh;
  int custom = (mode & PM_CUSTOM) != 0;
  int dw = custom ? lc_p8mem[CUSTOM_FONT] : 4;
  int dww = custom ? lc_p8mem[CUSTOM_FONT + 1] : 8;
  int dh = custom ? lc_p8mem[CUSTOM_FONT + 2] : 5;
  if (ch > 0x0f) {
    uint8_t rw;
    if (fw > -1 && fw < 4) rw = (uint8_t)(ch < 0x80 ? fw : fw + 4);
    else if (custom) rw = 8;              /* custom width only moves the cursor */
    else rw = (uint8_t)(ch < 0x80 ? dw : dww);
    if (ch >= 0x80) extra = dww - dw;
    uint8_t rh = (uint8_t)(fh > -1 && fh < 5 ? fh : dh);
    const uint8_t *g = custom ? &lc_p8mem[CUSTOM_FONT + ch * 8] : &lc_p8_font[ch * 8];
    extra += blit_glyph(g, x, y, fg, bg, mode, rw, rh, &eh);
  }
  if (mode & PM_ON) return 0;
  return extra;
}

/* print() at the cursor scrolls the real screen when the cursor falls
 * off the bottom: rows [start, start+keep) move to the top and the
 * `start` rows below them clear. Byte-for-byte FAKE-08, including the
 * reads/clears past 0x8000 when the cursor was poked far below. */
static void scroll(int y, int lh) {
  int keep = 127 - lh, start = y - keep;
  uint32_t dst = P8_SCREEN, src = P8_SCREEN + (uint32_t)start * 64;
  for (uint32_t i = 0; i < (uint32_t)keep * 64; i++) p8_wr8(dst + i, p8_rd8(src + i));
  dst = P8_SCREEN + (uint32_t)keep * 64;
  for (uint32_t i = 0; i < (uint32_t)start * 64; i++) p8_wr8(dst + i, 0);
  p8_wr8(P8_TEXT_Y, (uint8_t)keep);
}

/* printHelper print(str, x, y, c) */
static int print_at(const uint8_t *s, uint32_t len, int x, int y, uint8_t c) {
  lc_p8mem[P8_COLOR] = c;
  lc_p8mem[P8_TEXT_X] = (uint8_t)x;
  lc_p8mem[P8_TEXT_Y] = (uint8_t)y;

  int homex = x, homey = y, prevx = x, prevy = y;
  int tabw = 4, cw = 4, chh = 6, lh = 0, fw = -1, fh = -1, wrap = -1;
  uint8_t bg = 0xff, fg = lc_p8mem[P8_COLOR];
  uint8_t glyph[8] = {0};
  uint8_t ocol = 0, onb = 0;
  int nowrap = 0, underline = 0;
  const uint8_t *pal = &lc_p8mem[P8_DRAWPAL];

  uint8_t mode = lc_p8mem[P8_PRINTATTR];
  if (!(mode & PM_ON)) mode = 0;
  if (mode & PM_CUSTOM) {
    cw = lc_p8mem[CUSTOM_FONT];
    chh = lc_p8mem[CUSTOM_FONT + 2];
  }
#define FG pal[fg & 0x0f]
#define BG (bg == 0xff ? 0 : pal[bg & 0x0f])

  for (uint32_t n = 0; n < len; n++) {
    uint8_t ch = s[n];
    if (ch == 0) {                        /* \0: stop, cursor stays on this line */
      lc_p8mem[P8_TEXT_X] = (uint8_t)x;
      lc_p8mem[P8_TEXT_Y] = (uint8_t)y;
      return x;
    } else if (ch == 1) {                 /* \*p0c: repeat c */
      int times = p0(at(s, len, ++n));
      ch = at(s, len, ++n);
      for (int i = 0; i < times; i++)
        x += cw + draw_char(ch, x, y, FG, BG, mode, fw, fh);
    } else if (ch == 2) {                 /* \#p0: solid background */
      bg = p0(at(s, len, ++n));
      mode |= PM_ON | PM_SOLIDBG;
    } else if (ch == 3) {                 /* \-p0: x += p0-16 */
      x += p0(at(s, len, ++n)) - 16;
    } else if (ch == 4) {                 /* \|p0: y += p0-16 */
      y += p0(at(s, len, ++n)) - 16;
    } else if (ch == 5) {                 /* \+xy */
      int dx = p0(at(s, len, ++n)) - 16;
      int dy = p0(at(s, len, ++n)) - 16;
      x += dx;
      y += dy;
    } else if (ch == 6) {                 /* \^ commands */
      uint8_t cmd = at(s, len, ++n);
      if (cmd > 48 && cmd < 58) {
        /* \^1..\^9 frame pause: FAKE-08 does not yield */
      } else if (cmd == 'd') {
        n++;                              /* per-char delay: parsed, ignored */
      } else if (cmd == 'c') {
        lc_p8_cls(p0(at(s, len, ++n)));
      } else if (cmd == 'g') {
        x = homex;
        y = homey;
      } else if (cmd == 'h') {
        homex = x;
        homey = y;
      } else if (cmd == 'j') {
        uint8_t jx = at(s, len, ++n), jy = at(s, len, ++n);
        x = p0(jx) * 4;
        y = p0(jy) * 4;
      } else if (cmd == 'r') {
        wrap = p0(at(s, len, ++n)) * 4;
      } else if (cmd == 's') {
        tabw = p0(at(s, len, ++n));
      } else if (cmd == 'x') {
        fw = p0(at(s, len, ++n));
        cw = fw;
      } else if (cmd == 'y') {
        fh = p0(at(s, len, ++n));
        chh = fh;
      } else if (cmd == 'w') {
        mode |= PM_ON | PM_WIDE;
        cw = 8;
      } else if (cmd == 't') {
        mode |= PM_ON | PM_TALL;
        chh = 12;
      } else if (cmd == '=') {
        mode |= PM_ON | PM_STRIPEY;
      } else if (cmd == 'p') {
        mode |= PM_ON | PM_WIDE | PM_TALL | PM_STRIPEY;
        cw = 8;
        chh = 12;
      } else if (cmd == 'i') {
        mode |= PM_ON | PM_INVERT;
      } else if (cmd == 'b') {
        mode |= PM_ON | PM_PADDING;
      } else if (cmd == '#') {
        mode |= PM_ON | PM_SOLIDBG;
      } else if (cmd == ':' || cmd == ';' || cmd == '.' || cmd == ',') {
        /* one-off 8x8 glyph: 16 hex digits or 8 raw bytes */
        int eh;
        chh = fh > 0 ? fh : 8;
        if (cmd == ':' || cmd == ';') {
          uint32_t avail = n + 1 < len ? len - (n + 1) : 0;
          if (avail > 16) avail = 16;
          for (uint32_t i = 0; i < avail; i += 2) {
            uint8_t pair[2];
            pair[0] = s[n + 1 + i];
            pair[1] = i + 1 < avail ? s[n + 2 + i] : 0;
            glyph[i / 2] = (uint8_t)hexnum(pair, 2);
          }
          n += 16;
        } else {
          uint32_t avail = n + 1 < len ? len - (n + 1) : 0;
          for (uint32_t i = 0; i < 8; i++) glyph[i] = i < avail ? s[n + 1 + i] : 0;
          n += 8;
        }
        x += 8 + blit_glyph(glyph, x, y, FG, BG, mode, 8, (uint8_t)chh, &eh);
        chh = chh + eh;
        if (chh > lh) lh = chh;
      } else if (cmd == '-') {
        uint8_t off = at(s, len, ++n);
        if (mode) {
          if (off == 'w') { mode &= (uint8_t)~PM_WIDE; cw = 4; }
          else if (off == 't') { mode &= (uint8_t)~PM_TALL; chh = 6; }
          else if (off == '=') mode &= (uint8_t)~PM_STRIPEY;
          else if (off == 'p') {
            mode &= (uint8_t)~(PM_WIDE | PM_TALL | PM_STRIPEY);
            cw = 4;
            chh = 6;
          }
          else if (off == 'i') mode &= (uint8_t)~PM_INVERT;
          else if (off == 'b') mode &= (uint8_t)~PM_PADDING;
          else if (off == '#') mode &= (uint8_t)~PM_SOLIDBG;
        }
      } else if (cmd == '!') {
        /* \^!aaaa<rest>: poke the rest of the string (plus a trailing 0,
         * FAKE-08 copies one byte past the end) and stop */
        nowrap = 1;
        int32_t addr = hexfield(s, len, n + 1, 4);
        n += 4;
        int32_t size = n < len ? (int32_t)(len - n) : 0;
        for (int32_t i = 0; i < size; i++)
          pokeb(addr + i, at(s, len, n + 1 + (uint32_t)i));
        n += (uint32_t)size;
      } else if (cmd == '@') {
        /* \^@aaaassss<bytes>: poke ssss bytes */
        int32_t addr = hexfield(s, len, n + 1, 4);
        n += 4;
        int32_t size = hexfield(s, len, n + 1, 4);
        n += 4;
        if (size < 0) size = 0;           /* FAKE-08 overruns its buffer here */
        for (int32_t i = 0; i < size; i++)
          pokeb(addr + i, at(s, len, n + 1 + (uint32_t)i));
        n += (uint32_t)size;
      } else if (cmd == 'o') {
        /* \^ocnn: outline colour c, neighbour bitfield nn */
        ocol = p0(at(s, len, ++n));
        onb = (uint8_t)hexfield(s, len, n + 1, 2);
        n += 2;
      } else if (cmd == 'u') {
        underline = 1;
      }
    } else if (ch == 7) {                 /* \a sfx string: skipped up to a space */
      uint8_t c = at(s, len, ++n);
      while (c != 32 && n < len) c = at(s, len, ++n);
    } else if (ch == 11) {                /* \vp0c: decorate previous char */
      int off = p0(at(s, len, ++n));
      uint8_t c = at(s, len, ++n);
      draw_char(c, prevx + (off % 4) - 2, prevy + (off / 4) - 8, FG, BG, mode, fw, fh);
    } else if (ch == 12) {                /* \fp0: foreground colour */
      fg = p0(at(s, len, ++n));
      lc_p8mem[P8_COLOR] = fg;
    } else if (ch == 14) {                /* custom font on */
      mode |= PM_CUSTOM;
      cw = lc_p8mem[CUSTOM_FONT];
      chh = lc_p8mem[CUSTOM_FONT + 2];
    } else if (ch == 15) {                /* custom font off */
      mode &= (uint8_t)~PM_CUSTOM;
      cw = 4;
      chh = 6;
    } else if (ch == '\n') {
      x = homex;
      y += lh > 0 ? lh : 6;
      lh = 0;
    } else if (ch == '\t') {
      int stop = tabw * 4;
      if (stop != 0)                      /* FAKE-08 divides by zero here */
        while (x % stop > 0) x++;
    } else if (ch == '\b') {
      x -= cw;
    } else if (ch == '\r') {
      x = homex;
    } else if (ch >= 0x10) {
      if (chh > lh) lh = chh;
      if (mode & PM_SOLIDBG) {
        uint8_t pen = lc_p8mem[P8_COLOR];
        lc_p8_rectfill(x - 1, y - 1, x + cw - 1, y + lh - 1, bg);
        lc_p8mem[P8_COLOR] = pen;
      }
      prevx = x;
      prevy = y;
      if (ocol != 0 && onb != 0) {
        /* neighbours: 01 02 04 / 08 -- 10 / 20 40 80 */
        static const int8_t ox[8] = {-1, 0, 1, -1, 1, -1, 0, 1};
        static const int8_t oy[8] = {-1, -1, -1, 0, 0, 1, 1, 1};
        for (int i = 0; i < 8; i++)
          if (onb & (1 << i))
            draw_char(ch, x + ox[i], y + oy[i], pal[ocol & 0x0f], BG, mode, fw, fh);
      }
      if (underline)                      /* leaves the pen set to fg */
        lc_p8_rectfill(x - 1, y + lh, x + cw - 1, y + lh, fg);
      int extra = draw_char(ch, x, y, FG, BG, mode, fw, fh);
      /* custom font per-character width nibbles (0x5605 bit 0) */
      int adj = 0;
      if ((mode & PM_CUSTOM) && (lc_p8mem[CUSTOM_FONT + 5] & 1)) {
        int k = ch - 16;
        uint8_t b = lc_p8mem[CUSTOM_FONT + 8 + k / 2];
        adj = ((k & 1) ? (b >> 4) : b) & 7;
        if (adj >= 4) adj -= 8;
      }
      x += cw + extra + adj;
    }

    if (wrap > 0 && x >= wrap) {          /* \^r soft wrap */
      x = homex;
      y += lh > 0 ? lh : 6;
      lh = 0;
    }
  }
#undef FG
#undef BG

  lh = lh > 0 ? lh : nowrap ? 0 : 6;
  lc_p8mem[P8_TEXT_Y] = (uint8_t)(y + lh);
  return x;
}

int lc_p8_print(const uint8_t *s, uint32_t len, int has_xy, int x, int y, int has_col, int col) {
  if (has_xy)
    return print_at(s, len, x, y, has_col ? (uint8_t)col : lc_p8mem[P8_COLOR]);
  if (has_col) lc_p8mem[P8_COLOR] = (uint8_t)col;
  /* at the cursor: scroll first if it already sits off the bottom */
  if (lc_p8mem[P8_TEXT_Y] >= 127) scroll(lc_p8mem[P8_TEXT_Y], 6);
  int r = print_at(s, len, lc_p8mem[P8_TEXT_X], lc_p8mem[P8_TEXT_Y], lc_p8mem[P8_COLOR]);
  if (lc_p8mem[P8_TEXT_Y] >= 127) scroll(lc_p8mem[P8_TEXT_Y], 5);
  return r;
}

