/* luacretro runtime: PICO-8 audio, CHEAP engine for slow consoles.
 *
 * Selected at build time instead of the exact engine (lc_p8snd.c): an SDK
 * either compiles lc_p8snd.c with -DLC_P8SND_FAST (which includes this file
 * and nothing else) or compiles this file in place of lc_p8snd.c. Same public
 * API (lc_p8.h), plus the chip-voice calls lc_p8_audio_voices/advance.
 *
 * Two halves with different contracts:
 *
 *   SEQUENCER (exact). Everything stat() can see - sfx/music start, stop,
 *   loop, release, fade, note stepping, channel allocation, music patterns -
 *   runs on the exact engine's arithmetic: note offsets are the same soft
 *   doubles advanced in 22050 Hz ticks, the music fade the same soft float.
 *   What makes it cheap is that it does not step every tick. Inside one
 *   binade a repeated round-to-nearest add moves the mantissa by a constant
 *   (after at most one tick, when a tie-to-even settles), so a run of ticks
 *   is one multiply-add. The code finds how many ticks remain until the next
 *   tick that changes anything discrete (a note boundary, a loop wrap, an
 *   sfx end, a pattern end, a fade reaching zero, a pending music resume),
 *   jumps there, and replays only that tick with the exact engine's control
 *   code (copied from lc_p8snd.c, synthesis removed). stat(16..26, 46..57)
 *   therefore equals the exact engine's at every tick, not just per frame.
 *
 *   SYNTHESIS (approximate). Once per block (LC_P8SND_BLOCK output samples,
 *   and always at a note boundary) each channel's note is evaluated: pitch
 *   in Hz Q8 with slide / vibrato / drop / arpeggio applied, volume with
 *   fade in / out and the music fade, custom instruments through a small
 *   tick-counting sub-sequencer. Inside the block each channel is one or two
 *   32-bit phase accumulators reading 256-entry Q15 wavetables generated
 *   from the exact engine's waveform formulas (buzz variants included), or a
 *   one-pole lowpassed xorshift for noise (noiz supported). detune is a
 *   second oscillator (not for phaser, whose second oscillator is its own
 *   109/110 voice). Dropped: reverb, dampen (sfx filters and 0x5f41/0x5f43),
 *   the note-change crossfade, per-channel clamping. 0x5f40 (half rate) and
 *   0x5f42 (distort) are honoured.
 *
 * Output rate is LC_P8SND_RATE (default 22050); the sequencer always ticks
 * at 22050 Hz and output samples map onto ticks through a remainder
 * accumulator, so a GBA SDK can use 13379 or 10512 Hz and a Genesis SDK can
 * skip PCM entirely (lc_p8_audio_advance + lc_p8_audio_voices).
 *
 * Freestanding: stdint only, no float, no libc; 64-bit multiplies per block
 * and per sequencer event only, 32-bit work per sample.
 */
#include "lc_p8.h"

